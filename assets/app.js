/* Project shelves.
   Reads window.CATEGORIES and window.PROJECTS (both generated by
   scripts/sync-projects.py) and renders one shelf per category, each a
   bento grid of cards, with a filter bar that mirrors the URL hash. */
(function () {
  "use strict";

  var T = {
    en: {
      tagline: "Games, tools and small apps — all home-made.",
      stats: "{n} projects · {l} live · {c} shelves",
      all: "All", live: "Live", repo: "Repo",
      active: "active {t}", stars: "{n} stars",
      langgroup: "Language", filterlabel: "Filter by category",
      footnote: "Pulled straight from GitHub, sorted by topic.",
      title: "Daniel Rck · Projects"
    },
    de: {
      tagline: "Spiele, Werkzeuge und kleine Apps — alles selbst gebaut.",
      stats: "{n} Projekte · {l} live · {c} Regale",
      all: "Alle", live: "Live", repo: "Repo",
      active: "aktiv {t}", stars: "{n} Sterne",
      langgroup: "Sprache", filterlabel: "Nach Kategorie filtern",
      footnote: "Direkt aus GitHub gelesen, nach Thema sortiert.",
      title: "Daniel Rck · Projekte"
    }
  };

  var P = window.PROJECTS || [];
  // Only shelves that actually hold something are shown.
  var C = (window.CATEGORIES || []).filter(function (c) {
    return P.some(function (p) { return p.category === c.id; });
  });

  var reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  var lang = "en";
  var filter = "all";

  function t(k, vars) {
    return T[lang][k].replace(/\{(\w)\}/g, function (_, v) { return vars[v]; });
  }

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }

  function hue(node, cat) {
    if (!cat || !cat.color) return;
    node.style.setProperty("--hue-d", cat.color.dark);
    node.style.setProperty("--hue-l", cat.color.light);
  }

  function pad(n) { return (n < 10 ? "0" : "") + n; }

  function inCat(id) { return P.filter(function (p) { return p.category === id; }); }

  /* "3 days ago" / "vor 3 Tagen", coarsest unit that is at least 1 */
  var UNITS = [["year", 31536e6], ["month", 2592e6], ["week", 6048e5], ["day", 864e5], ["hour", 36e5]];
  function ago(iso) {
    if (!iso || !window.Intl || !Intl.RelativeTimeFormat) return null;
    var diff = new Date(iso).getTime() - Date.now();
    var fmt = new Intl.RelativeTimeFormat(lang, { numeric: "auto" });
    for (var i = 0; i < UNITS.length; i++) {
      var n = Math.round(diff / UNITS[i][1]);
      if (Math.abs(n) >= 1) return fmt.format(n, UNITS[i][0]);
    }
    return fmt.format(0, "hour");
  }

  function link(cls, text, href) {
    var a = el("a", cls, text);
    a.href = href; a.target = "_blank"; a.rel = "noopener";
    return a;
  }

  /* ------------------------------------------------------------------ *
   * header
   * ------------------------------------------------------------------ */
  function buildHeader() {
    var live = P.filter(function (p) { return p.live; }).length;
    document.getElementById("stats").textContent =
      t("stats", { n: P.length, l: live, c: C.length });

    var spec = document.getElementById("spectrum");
    spec.innerHTML = "";
    C.forEach(function (c) {
      var s = el("span");
      s.style.flexGrow = inCat(c.id).length;
      hue(s, c);
      spec.appendChild(s);
    });
  }

  /* ------------------------------------------------------------------ *
   * filter bar
   * ------------------------------------------------------------------ */
  function buildFilters() {
    var bar = document.getElementById("filters");
    bar.innerHTML = "";
    [{ id: "all" }].concat(C).forEach(function (c) {
      var b = el("button", "chip");
      b.type = "button";
      b.dataset.cat = c.id;
      if (c.id === "all") {
        b.appendChild(el("span", null, t("all")));
        b.appendChild(el("span", "n", String(P.length)));
      } else {
        hue(b, c);
        b.appendChild(el("i", "dot"));
        b.appendChild(el("span", null, c.label[lang]));
        b.appendChild(el("span", "n", String(inCat(c.id).length)));
      }
      b.addEventListener("click", function () { setFilter(c.id, true); });
      bar.appendChild(b);
    });
  }

  function setFilter(id, push) {
    if (id !== "all" && !C.some(function (c) { return c.id === id; })) id = "all";
    filter = id;
    Array.prototype.forEach.call(document.querySelectorAll(".chip"), function (b) {
      b.setAttribute("aria-pressed", String(b.dataset.cat === id));
    });
    Array.prototype.forEach.call(document.querySelectorAll(".shelf"), function (s) {
      var show = id === "all" || s.dataset.cat === id;
      s.hidden = !show;
      if (show && !reduce) {
        s.classList.remove("swap");
        void s.offsetWidth;             // restart the fade
        s.classList.add("swap");
      }
    });
    if (push) {
      var hash = id === "all" ? "" : "#" + id;
      history.replaceState(null, "", location.pathname + location.search + hash);
      var top = document.getElementById("filters").offsetTop;
      if (window.scrollY > top) window.scrollTo({ top: top, behavior: reduce ? "auto" : "smooth" });
    }
  }

  window.addEventListener("hashchange", function () {
    setFilter(location.hash.slice(1) || "all", false);
  });

  /* ------------------------------------------------------------------ *
   * shelves and cards
   * ------------------------------------------------------------------ */
  // The lead card of each shelf (featured, else live, else most recent —
  // that is the sync's order) and anything featured spans two columns.
  function card(p, cat, lead) {
    var wide = lead || !!p.featured;
    var a = el("article", "card" + (wide ? " wide" : ""));
    hue(a, cat);

    var top = el("div", "card-top");
    var glyph = el("span", "glyph", p.emoji);
    glyph.setAttribute("aria-hidden", "true");
    top.appendChild(glyph);
    top.appendChild(el("span", "owner", p.owner));
    a.appendChild(top);

    if (wide) {
      var ghost = el("span", "ghost", p.emoji);
      ghost.setAttribute("aria-hidden", "true");
      a.appendChild(ghost);
    }

    a.appendChild(el("h3", null, p.name));
    if (p.desc[lang]) a.appendChild(el("p", "desc", p.desc[lang]));

    if (p.tech && p.tech.length) {
      var chips = el("ul", "tech");
      p.tech.forEach(function (x) { chips.appendChild(el("li", null, x)); });
      a.appendChild(chips);
    }

    var foot = el("div", "card-foot");
    var meta = [];
    var when = ago(p.pushed);
    if (when) meta.push(t("active", { t: when }));
    if (p.stars > 0) meta.push("★ " + p.stars);
    var m = el("span", "meta", meta.join(" · "));
    if (p.stars > 0) m.title = t("stars", { n: p.stars });
    foot.appendChild(m);

    var acts = el("div", "acts");
    if (p.live) acts.appendChild(link("btn primary", t("live") + " ↗", p.live));
    acts.appendChild(link("btn", t("repo"), p.repo));
    foot.appendChild(acts);
    a.appendChild(foot);
    return a;
  }

  var seen = null;
  function buildShelves() {
    var host = document.getElementById("shelves");
    host.innerHTML = "";
    C.forEach(function (c, i) {
      var s = el("section", "shelf");
      s.dataset.cat = c.id;
      s.id = "shelf-" + c.id;
      hue(s, c);

      var head = el("header", "shelf-head");
      var titles = el("div", "titles");
      titles.appendChild(el("span", "no", pad(i + 1) + " / " + pad(C.length)));
      titles.appendChild(el("h2", null, c.label[lang]));
      if (c.blurb) titles.appendChild(el("p", null, c.blurb[lang]));
      head.appendChild(titles);
      head.appendChild(el("span", "count", String(inCat(c.id).length)));
      s.appendChild(head);

      var grid = el("div", "grid");
      inCat(c.id).forEach(function (p, k) {
        var node = card(p, c, k === 0);
        node.style.setProperty("--k", k);
        grid.appendChild(node);
      });
      s.appendChild(grid);
      host.appendChild(s);
    });

    // Staggered reveal, once per card. Without an observer (or with reduced
    // motion) everything is simply visible.
    if (reduce || !("IntersectionObserver" in window)) return;
    document.documentElement.classList.add("motion");
    if (seen) seen.disconnect();
    seen = new IntersectionObserver(function (entries) {
      entries.forEach(function (e) {
        if (!e.isIntersecting) return;
        e.target.classList.add("in");
        seen.unobserve(e.target);
      });
    }, { rootMargin: "0px 0px -8% 0px" });
    Array.prototype.forEach.call(host.querySelectorAll(".card"), function (n) { seen.observe(n); });
  }

  /* ------------------------------------------------------------------ *
   * language
   * ------------------------------------------------------------------ */
  function setLang(l) {
    lang = l;
    try { localStorage.setItem("lang", l); } catch (e) { /* private mode */ }
    document.documentElement.lang = l;
    document.title = t("title");

    Array.prototype.forEach.call(document.querySelectorAll("[data-i18n]"), function (n) {
      n.textContent = t(n.dataset.i18n);
    });
    Array.prototype.forEach.call(document.querySelectorAll("[data-i18n-label]"), function (n) {
      n.setAttribute("aria-label", t(n.dataset.i18nLabel));
    });
    Array.prototype.forEach.call(document.querySelectorAll(".lang button"), function (b) {
      b.setAttribute("aria-pressed", String(b.dataset.lang === l));
    });

    buildHeader();
    buildFilters();
    buildShelves();
    setFilter(filter, false);
  }

  Array.prototype.forEach.call(document.querySelectorAll(".lang button"), function (b) {
    b.addEventListener("click", function () { setLang(b.dataset.lang); });
  });

  /* ------------------------------------------------------------------ *
   * boot
   * ------------------------------------------------------------------ */
  filter = location.hash.slice(1) || "all";
  var start = (navigator.language || "").slice(0, 2) === "de" ? "de" : "en";
  try {
    var stored = localStorage.getItem("lang");
    if (stored === "de" || stored === "en") start = stored;
  } catch (e) { /* private mode */ }
  setLang(start);
})();
